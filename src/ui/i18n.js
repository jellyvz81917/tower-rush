export const selectLanguage = (platformLanguage, browserLanguage = 'ru') => {
  const language = String(platformLanguage || browserLanguage).toLowerCase().split('-')[0];
  return language === 'ru' ? 'ru' : 'en';
};
export const translator = language => text => language === 'en' ? (en[text] || text) : text;

export function translateDocument(document, language) {
  document.documentElement.lang = language;
  if (language !== 'en') return;
  const t = translator(language);
  const walker = document.createTreeWalker(document.body, 4);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    if (['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(node.parentElement?.tagName)) continue;
    const key = node.textContent.trim().replace(/\s+/g, ' ');
    if (en[key]) node.textContent = node.textContent.replace(node.textContent.trim(), t(key));
  }
  for (const element of document.querySelectorAll('[aria-label], [title]')) {
    for (const attribute of ['aria-label', 'title']) {
      const value = element.getAttribute(attribute);
      if (value && en[value]) element.setAttribute(attribute, t(value));
    }
  }
  document.title = 'Tower Rush — Build a Skyscraper';
}
